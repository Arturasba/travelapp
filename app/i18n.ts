export type Message = keyof typeof lt;
export function translator(locale: Locale) { return (message: Message): string => locale === "lt" ? lt[message] : message; }
export function sourceLabel(label: string, locale: Locale) { return locale === "lt" && label in lt ? lt[label as Message] : label; }
export function placeWord(count: number, locale: Locale) {
  if (locale === "en") return count === 1 ? "place" : "places";
  return count % 10 === 1 && count % 100 !== 11 ? "vieta" : count % 10 >= 2 && count % 10 <= 9 && !(count % 100 >= 11 && count % 100 <= 19) ? "vietos" : "vietų";
}
export function localizeDestination(place: Destination, locale: Locale): Destination {
  if (locale === "en") return place;
  const translated = (lithuanian as Record<string, {name:string;description:string;reasons:string[];visitorInfo:string[];coordinateNote:string;cuisine?:string}>)[place.slug];
  if (!translated) throw new Error(`Missing Lithuanian destination: ${place.slug}`);
  const location = place.location.replace(/Lithuania/g,"Lietuva").replace(/Vilnius County/g,"Vilniaus apskritis").replace(/Curonian Spit/g,"Kuršių nerija").replace(/Castle Hill/g,"Pilies kalnas").replace(/near Šiauliai/g,"prie Šiaulių").replace(/Baltic coast/g,"Baltijos pajūris").replace(/Nemunas valley/g,"Nemuno slėnis").replace(/Neris valley/g,"Neries slėnis").replace(/Pavilniai Regional Park/g,"Pavilnių regioninis parkas").replace(/Southern Lietuva/g,"Pietų Lietuva").replace(/Birutė Park/g,"Birutės parkas").replace(/Kaunas Reservoir/g,"Kauno marios").replace(/Žemaitija National Park/g,"Žemaitijos nacionalinis parkas");
  const localLocation=location.replace(/Jurbarkas District/g,"Jurbarko rajonas").replace(/Anykščiai District/g,"Anykščių rajonas").replace(/Varėna District/g,"Varėnos rajonas").replace(/Širvintos District/g,"Širvintų rajonas").replace(/Plungė District/g,"Plungės rajonas");
  return {...place,...translated,location:localLocation,photos:place.photos.map(photo=>({...photo,alt:translated.name}))};
}
